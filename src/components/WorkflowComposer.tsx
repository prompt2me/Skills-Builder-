import React, { useState } from 'react';
import { GitMerge, Plus, ArrowRight, Play, Download, Trash2, CheckCircle2, Layers } from 'lucide-react';
import { Skill, MultiSkillWorkflow, WorkflowStage } from '../types/skill.ts';
import { downloadSingleFile } from '../lib/exportUtils.ts';

interface WorkflowComposerProps {
  skills: Skill[];
  onOpenSkill: (skill: Skill) => void;
}

export const WorkflowComposer: React.FC<WorkflowComposerProps> = ({ skills, onOpenSkill }) => {
  const [workflows, setWorkflows] = useState<MultiSkillWorkflow[]>([
    {
      id: 'wf-growth-engine',
      name: 'End-to-End Growth & SEO Content Pipeline',
      description: 'Chains competitive intelligence into data analysis, content brief generation, and automated validation.',
      createdAt: '2026-11-02T12:00:00.000Z',
      stages: [
        {
          id: 'stage-1',
          skillId: skills[0]?.id || 'skill-seo-intelligence',
          stageName: '1. Competitor Search Discovery',
          inputMapping: 'Target market domain & competitor list',
          outputArtifact: 'Topical gap matrix & priority search queries',
        },
        {
          id: 'stage-2',
          skillId: skills[1]?.id || 'skill-excel-dashboard',
          stageName: '2. Search Opportunity Scoring & Modeling',
          inputMapping: 'Search volume & difficulty matrices',
          outputArtifact: 'Ranked opportunity index & traffic forecasts',
        },
        {
          id: 'stage-3',
          skillId: skills[2]?.id || 'skill-ts-architect',
          stageName: '3. Technical Implementation & Briefs',
          inputMapping: 'Prioritized content & schema requirements',
          outputArtifact: 'Complete production markdown briefs & metadata',
        },
      ],
    },
  ]);

  const [activeWorkflow, setActiveWorkflow] = useState<MultiSkillWorkflow>(workflows[0]);
  const [showAddStageModal, setShowAddStageModal] = useState(false);
  const [selectedSkillId, setSelectedSkillId] = useState(skills[0]?.id || '');
  const [stageName, setStageName] = useState('');
  const [inputMapping, setInputMapping] = useState('');
  const [outputArtifact, setOutputArtifact] = useState('');

  const handleAddStage = () => {
    if (!stageName || !selectedSkillId) return;

    const newStage: WorkflowStage = {
      id: `stage-${Date.now()}`,
      skillId: selectedSkillId,
      stageName,
      inputMapping: inputMapping || 'Previous stage output artifact',
      outputArtifact: outputArtifact || 'Structured deliverable',
    };

    const updated = {
      ...activeWorkflow,
      stages: [...activeWorkflow.stages, newStage],
    };

    setActiveWorkflow(updated);
    setWorkflows(workflows.map((w) => (w.id === updated.id ? updated : w)));
    setShowAddStageModal(false);
    setStageName('');
    setInputMapping('');
    setOutputArtifact('');
  };

  const handleDeleteStage = (stageId: string) => {
    const updated = {
      ...activeWorkflow,
      stages: activeWorkflow.stages.filter((s) => s.id !== stageId),
    };
    setActiveWorkflow(updated);
    setWorkflows(workflows.map((w) => (w.id === updated.id ? updated : w)));
  };

  const handleExportWorkflow = () => {
    const markdown = `# ${activeWorkflow.name}

${activeWorkflow.description}

## Chained Claude Skill Execution Pipeline

${activeWorkflow.stages
  .map((st, idx) => {
    const matchedSkill = skills.find((s) => s.id === st.skillId);
    return `### Stage ${idx + 1}: ${st.stageName}
- **Assigned Claude Skill:** \`${matchedSkill?.name || 'custom-skill'}\`
- **Input Contract:** ${st.inputMapping}
- **Output Artifact:** ${st.outputArtifact}
`;
  })
  .join('\n\n')}

---
Generated by **AI Skill Architect Workflow Composer**
`;

    downloadSingleFile(`${activeWorkflow.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.md`, markdown);
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8 space-y-8">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900 tracking-tight">Multi-Skill Workflow Composer</h1>
          <p className="text-xs sm:text-sm text-slate-500">
            Chain modular Claude Skills into end-to-end multi-agent pipelines with explicit data contracts.
          </p>
        </div>

        <button
          onClick={handleExportWorkflow}
          className="inline-flex items-center gap-1.5 px-4 py-2 bg-blue-600 hover:bg-blue-700 text-white text-xs sm:text-sm font-semibold rounded-lg shadow-sm transition-all"
        >
          <Download className="w-4 h-4" />
          <span>Export Workflow Spec</span>
        </button>
      </div>

      {/* Main Pipeline Flow Canvas */}
      <div className="bg-white rounded-2xl border border-slate-200 p-6 shadow-sm space-y-6">
        <div className="flex items-center justify-between border-b border-slate-100 pb-4">
          <div>
            <h2 className="text-lg font-bold text-slate-900">{activeWorkflow.name}</h2>
            <p className="text-xs text-slate-500">{activeWorkflow.description}</p>
          </div>
          <button
            onClick={() => setShowAddStageModal(true)}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-800 text-xs font-semibold rounded-lg transition-colors"
          >
            <Plus className="w-3.5 h-3.5" />
            <span>Add Pipeline Stage</span>
          </button>
        </div>

        {/* Sequential Stages List */}
        <div className="space-y-4">
          {activeWorkflow.stages.map((stage, idx) => {
            const matchedSkill = skills.find((s) => s.id === stage.skillId);

            return (
              <div key={stage.id} className="relative">
                <div className="p-5 rounded-xl border border-slate-200 hover:border-blue-400 bg-slate-50/60 transition-all space-y-3">
                  <div className="flex items-start justify-between">
                    <div className="flex items-center gap-2">
                      <span className="w-6 h-6 rounded-full bg-blue-600 text-white text-xs font-bold flex items-center justify-center">
                        {idx + 1}
                      </span>
                      <h3 className="font-bold text-sm text-slate-900">{stage.stageName}</h3>
                    </div>

                    <div className="flex items-center gap-2">
                      {matchedSkill && (
                        <button
                          onClick={() => onOpenSkill(matchedSkill)}
                          className="text-xs text-blue-600 hover:underline font-mono"
                        >
                          {matchedSkill.name}
                        </button>
                      )}
                      <button
                        onClick={() => handleDeleteStage(stage.id)}
                        className="p-1 text-slate-400 hover:text-rose-600 transition-colors"
                        title="Delete stage"
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>
                  </div>

                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs pt-1">
                    <div className="p-2.5 rounded-lg bg-white border border-slate-200">
                      <span className="font-semibold text-slate-500 uppercase text-[10px] block">Input Contract</span>
                      <span className="text-slate-700">{stage.inputMapping}</span>
                    </div>

                    <div className="p-2.5 rounded-lg bg-white border border-slate-200">
                      <span className="font-semibold text-slate-500 uppercase text-[10px] block">Output Artifact</span>
                      <span className="text-slate-700">{stage.outputArtifact}</span>
                    </div>
                  </div>
                </div>

                {idx < activeWorkflow.stages.length - 1 && (
                  <div className="flex justify-center my-1 text-slate-400">
                    <div className="h-4 w-px bg-slate-300" />
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>

      {/* Add Stage Modal */}
      {showAddStageModal && (
        <div className="fixed inset-0 z-50 bg-slate-900/40 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-xl shadow-xl border border-slate-200 p-5 max-w-md w-full space-y-4">
            <h3 className="font-bold text-slate-900 text-base">Add Stage to Workflow</h3>

            <div className="space-y-3 text-xs">
              <div>
                <label className="block font-semibold text-slate-700 mb-1">Stage Title</label>
                <input
                  type="text"
                  value={stageName}
                  onChange={(e) => setStageName(e.target.value)}
                  placeholder="e.g. Editorial Review & Fact-Checking"
                  className="w-full bg-slate-50 border border-slate-300 rounded-lg px-3 py-2 text-slate-800"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">Assigned Claude Skill</label>
                <select
                  value={selectedSkillId}
                  onChange={(e) => setSelectedSkillId(e.target.value)}
                  className="w-full bg-slate-50 border border-slate-300 rounded-lg px-3 py-2 text-slate-800"
                >
                  {skills.map((s) => (
                    <option key={s.id} value={s.id}>
                      {s.displayName || s.name}
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">Input Contract</label>
                <input
                  type="text"
                  value={inputMapping}
                  onChange={(e) => setInputMapping(e.target.value)}
                  placeholder="e.g. Draft markdown article from Stage 2"
                  className="w-full bg-slate-50 border border-slate-300 rounded-lg px-3 py-2 text-slate-800"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">Output Deliverable</label>
                <input
                  type="text"
                  value={outputArtifact}
                  onChange={(e) => setOutputArtifact(e.target.value)}
                  placeholder="e.g. Verified publication copy & changelog"
                  className="w-full bg-slate-50 border border-slate-300 rounded-lg px-3 py-2 text-slate-800"
                />
              </div>
            </div>

            <div className="flex justify-end gap-2 pt-2">
              <button
                type="button"
                onClick={() => setShowAddStageModal(false)}
                className="px-3 py-1.5 text-xs text-slate-600 hover:bg-slate-100 rounded-lg font-medium"
              >
                Cancel
              </button>
              <button
                type="button"
                onClick={handleAddStage}
                className="px-4 py-1.5 text-xs bg-blue-600 hover:bg-blue-700 text-white rounded-lg font-semibold"
              >
                Add Stage
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
