import JSZip from 'jszip';
import { Skill } from '../types/skill.ts';

export function downloadSingleFile(filename: string, content: string, mimeType = 'text/markdown') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function downloadZipPackage(skill: Skill, includeMetadata = true) {
  const zip = new JSZip();
  const folderName = skill.name || 'custom-skill';
  const root = zip.folder(folderName);

  if (!root) throw new Error('Failed to create zip folder');

  // Add all files
  for (const file of skill.files) {
    root.file(file.path, file.content);
  }

  // Include metadata bundle if requested
  if (includeMetadata) {
    const metaFolder = root.folder('.metadata');
    if (metaFolder) {
      metaFolder.file(
        'requirements.json',
        JSON.stringify(skill.requirements, null, 2)
      );
      metaFolder.file(
        'validation-report.json',
        JSON.stringify(skill.validationReport, null, 2)
      );
      metaFolder.file(
        'test-suite.json',
        JSON.stringify(
          { testCases: skill.testCases, testResults: skill.testResults },
          null,
          2
        )
      );
    }
  }

  // Add README.md with installation instructions
  const readmeContent = `# ${skill.displayName || skill.name}

${skill.description}

## Installation in Claude Code
To install this skill locally for the Claude Code CLI:

\`\`\`bash
# Create the skill directory in your Claude config
mkdir -p ~/.claude/skills/${folderName}

# Copy the skill files into place
cp -r * ~/.claude/skills/${folderName}/
\`\`\`

## Installation in Claude Desktop / Projects
1. Open Claude Desktop or claude.ai
2. Navigate to your Project settings
3. Add \`SKILL.md\` to Project Knowledge or Custom Instructions
4. Attach files from \`references/\` and \`templates/\` as project files.

---
Generated by **AI Skill Architect**
`;
  root.file('README.md', readmeContent);

  const content = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(content);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${folderName}.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch (err) {
    console.error('Clipboard copy failed:', err);
    return false;
  }
}
